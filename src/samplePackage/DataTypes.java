package samplePackage;

public class DataTypes {
	public static void main(String args[]) {
		byte myByte = 127;  // byte
		short myShort = 5000; // short
		int myInt = 65000; // integer
		long myLong = 1000000; // long
		float myFloat = 10.034456784567856f; // float
		double myDouble = 314159.123456788765432345678987654345678987654;  // double
		boolean myBoolean = true; // boolean
		char myChar = 'h'; // char
		
		System.out.println(myByte);
		System.out.println(myShort);
		System.out.println(myInt);
		System.out.println(myLong);
		System.out.println(myFloat);
		System.out.println(myDouble);
		System.out.println(myBoolean);
		System.out.println(myChar);
	}
	
	
	
}
